    private void txtSerialNoKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtSerialNoKeyPressed
        // TODO add your handling code here:
        if (evt.getKeyCode() == KeyEvent.VK_ENTER)
        {
            try {
                String serial_number = txtSerialNo.getText();
                
                statementP = connectDB.prepareStatement("SELECT * FROM car WHERE serial_id = ?");
                statementP.setString(1, serial_number);
                resultS = statementP.executeQuery();
                
                if(resultS.next() == false)
                {
                    JOptionPane.showMessageDialog(this, "Serial Number not found!");
                }
                else{
                    String car_make = resultS.getString("make");
                    txtMake.setText(car_make.trim());
                    
                    String car_model = resultS.getString("model");
                    txtModel.setText(car_model.trim());

                    String car_year = resultS.getString("year");
                    txtYear.setText(car_year.trim());

                    String car_price = resultS.getString("price");
                    txtPrice.setText(car_price.trim());

                    sQuality.requestFocus();
                    
                }
                
            } catch (SQLException ex) {
                System.getLogger(CarwowFrame.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }
        }
    }//GEN-LAST:event_txtSerialNoKeyPressed


    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        try{
            int carPrice = Integer.parseInt(txtPrice.getText().trim());
            int carQty = Integer.parseInt(sQuality.getValue().toString());
        
            int totalPrice = carPrice * carQty;
        
            dataCenter.addRowToJFrame(new Object[] {
                    txtMake.getText(),
                    txtModel.getText(),
                    txtYear.getText(), 
                    carPrice,
                    carQty,
                    totalPrice  
            }); 
            
            int sum = 0;
            for (int i = 0; i < datacenterFrame.carTable.getRowCount(); i++)
            {
                sum = sum + Integer.parseInt(datacenterFrame.carTable.getValueAt(1, 3).toString());
            }
            txtTotalCost.setText(String.valueOf(sum));
            txtMake.setText("");
            txtModel.setText("");
            txtYear.setText("");
            txtPrice.setText("");
            sQuality.setValue(0);
            txtMake.setText("");
            txtTotalCost.requestFocus();
         }catch(NumberFormatException e){
         
         }
                
    }//GEN-LAST:event_btnAddActionPerformed

