    public void sales()
    {

        try {
            
            String totalCT = txtTotalCost.getText();
            String pay = txtPay.getText();
            int balance = 0;

            if (!txtBalance.getText().isEmpty()) {
                balance = Integer.parseInt(txtBalance.getText());
            }

            int lastid = 0;
            String query = "insert into sales(subTotal,pay,balance)values(?,?,?)";
        
            statementP = connectDB.prepareStatement(query,Statement.RETURN_GENERATED_KEYS);
            statementP.setString(1,totalCT);
            statementP.setString(2,pay);
            statementP.setInt(3,balance);
            statementP.executeUpdate();
            resultS = statementP.getGeneratedKeys();
            if(resultS.next())
            {
                lastid = resultS.getInt(1);
            }
            int rows = datacenterFrame.carTable.getRowCount();
            String query1 = "insert into saleProduct(saleID,cMake,price,qty,total)values(?,?,?,?,?)";
            statementP2 = connectDB.prepareStatement(query1);
            
            String carMake;
            int carPrice;
            int carQty;
            int total = 0;
            
            for (int i = 0; i < rows; i ++)
            {
                carMake = (String) datacenterFrame.carTable.getValueAt(i, 0);
                carPrice = (int) datacenterFrame.carTable.getValueAt(i, 3);
                carQty = (int) datacenterFrame.carTable.getValueAt(i, 4);
                total = (Integer) datacenterFrame.carTable.getValueAt(i, 5);
                
                statementP2.setInt(1, lastid);
                statementP2.setString(2, carMake);
                statementP2.setInt(3, carPrice);
                statementP2.setInt(4, carQty);
                statementP2.setInt(5, total);
                
                statementP2.executeUpdate();
                
            }
            JOptionPane.showMessageDialog(this, "Sales Completed!");
        } catch (SQLException ex) {
            System.getLogger(CarwowFrame.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    
    }
    

